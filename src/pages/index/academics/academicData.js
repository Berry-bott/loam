export const academicItems = academicSections.flatMap((section) =>
  section.items.map((item) => ({
    ...item,
    category: section.title,
    queryKey: item.queryKey || item.slug,
    href: `/academics?${item.queryKey || item.slug}`,
  })),
)

export function getAcademicItemByIdentifier(identifier) {
  return academicItems.find((item) => item.slug === identifier || item.queryKey === identifier)
}
